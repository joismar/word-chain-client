describe('game', () => {
  const playing = (extra: Partial<PlayState> = {}, state: Partial<GameState> = {}): PlayState => ({
    game: game({
      status: 'playing',
      turnPlayerId: 'a',
      chain: [{ word: 'casa', playerId: null }, { word: 'sapo', playerId: 'a' }, { word: 'pote', playerId: 'b' }],
      ...state,
    }),
    playerId: 'a',
    times: { startsIn: 0, match: 125, turn: 8 },
    typed: '',
    focused: true,
    pending: false,
    ...extra,
  });

  it('lays the chain out as a staircase over the input on my turn', () => {
    const scene = gameScene(playing({ typed: 'TE' }), area);
    expect(scene.fields).toEqual([{ id: 'word', row: 3, col: -6, length: 12, label: 'Palavra', value: 'TE' }]);
    expect(ascii(scene, area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      .2:05.......8S.
      ...............
      ...............
      ...............
      ...............
      ...CASA........
      .....SAPO......
      .......POTE....
      ...............
      .TE|_________..
      ...............
      .PASSAR.....↵..
      ...............
      ...............
      ...............
      "
    `);
    expect(words(scene.tiles)).toMatchInlineSnapshot(`
      "
      match "2:05" @-6,-6 stone
      turn "8S" @-6,5 rose
      chain-0 "CASA" @-1,-4 stone
      chain-1 "SAPO" @0,-2 emerald/stone
      chain-2 "POTE" @1,0 emerald/amber
      chain-3 "TE__________" @3,-6 amber
      pass "PASSAR" @5,-6 rose -> pass
      submit "↵" @5,5 emerald -> submit
      "
    `);
  });

  it('shows whose turn it is to everyone else', () => {
    const scene = gameScene(playing({ playerId: 'b' }), area);
    expect(scene.fields).toEqual([]);
    expect(ascii(scene, area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      .2:05.......8S.
      ...............
      ...............
      ...............
      ...............
      ...CASA........
      .....SAPO......
      .......POTE....
      ...............
      ..VEZ.DE.ANA...
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
  });

  it('counts down to the start without a turn clock', () => {
    const scene = gameScene(playing({ times: { startsIn: 3, match: 180, turn: 30 } }), area);
    expect(ascii(scene, area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      .3:00..........
      ...............
      ...............
      ...............
      ...............
      ...CASA........
      .....SAPO......
      .......POTE....
      ...............
      ..COMECA.EM.3..
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
  });

  it('turns the clocks rose near the end', () => {
    const scene = gameScene(playing({ times: { startsIn: 0, match: 30, turn: 5 } }), area);
    expect(words(scene.tiles.filter((t) => /^(match|turn):/.test(t.key)))).toMatchInlineSnapshot(`
      "
      match "0:30" @-6,-6 rose
      turn "5S" @-6,5 rose
      "
    `);
  });

  it('disables pass and submit while a word is pending', () => {
    const scene = gameScene(playing({ typed: 'TELA', pending: true }), area);
    expect(scene.tiles.filter((t) => t.action)).toEqual([]);
  });

  it('types into the tiles of the next chain word, so an accepted word flies into place', () => {
    const before = playing({ typed: 'TELA' });
    const typing = gameScene(before, area).tiles.filter((t) => t.key.startsWith(`${inputWordId(before.game)}:`));
    const after = gameScene(playing({}, {
      turnPlayerId: 'b',
      chain: [...before.game.chain, { word: 'tela', playerId: 'a' }],
    }), area);
    const landed = after.tiles.filter((t) => t.key.startsWith('chain-3:'));
    expect(landed.map((t) => t.char).join('')).toBe('TELA');
    expect(keysOf(landed)).toEqual(keysOf(typing).slice(0, 4));
    expect(landed.every((t) => t.row === 1)).toBe(true);
  });

  it('scrolls old words off the top, keeping their keys while they climb', () => {
    const chain = ['casa', 'sapo', 'pote', 'tela', 'lago', 'gota', 'tampa', 'pato'].map((word) => ({ word, playerId: 'a' }));
    const tiles = chainTiles(game({ chain }), area);
    const ids = [...new Set(tiles.map((t) => t.key.split(':')[0]))];
    expect(ids).toHaveLength(CHAIN_ROWS);
    expect(ids[0]).toBe(`chain-${chain.length - CHAIN_ROWS}`);
    const rows = new Set(tiles.filter((t) => t.key.startsWith('chain-7:')).map((t) => t.row));
    expect([...rows]).toEqual([1]);
    expect(ascii(gameScene(playing({}, { chain }), area), area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      .2:05.......8S.
      ...............
      POTE...........
      ..TELA.........
      ....LAGO.......
      ......GOTA.....
      ........TAMPA..
      ...........PATO
      ...............
      .|___________..
      ...............
      .PASSAR.....↵..
      ...............
      ...............
      ...............
      "
    `);
  });

  it('cuts a word longer than the board at the right edge, keeping its start', () => {
    const chain = [{ word: 'otorrinolaringologista', playerId: null }];
    const tiles = gameScene(playing({}, { chain }), area).tiles.filter((t) => t.key.startsWith('chain-0:'));
    expect(tiles.map((t) => t.char).join('')).toBe('OTORRINOLARINGO');
  });
});

