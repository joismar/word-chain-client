describe('lobby', () => {
  const lobby = (extra: Partial<LobbyState> = {}): LobbyState => ({
    game: game(), playerId: 'a', copied: false, readyPending: false, startPending: false,
    settings: false, config: { time: 3, repetition: true }, ...extra,
  });

  it('lists only the players on the board, with their ready mark after the longest name', () => {
    const scene = lobbyScene(lobby(), area);
    expect(ascii(scene, area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      .....ANA.✓.....
      .....BIA.✕.....
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
    expect(words(scene.tiles)).toMatchInlineSnapshot(`
      "
      player-a "ANA" @-1,-2 rose
      status-a "✓" @-1,2 emerald
      player-b "BIA" @0,-2 sky
      status-b "✕" @0,2 rose
      "
    `);
    expect(hud(scene.hud)).toMatchInlineSnapshot(`
      "
      bar: < -> leave · "SALA: CASAS" · copy · ⚙
      action: ready "ESPERAR" stone
      action: start "INICIAR" amber primary
      "
    `);
  });

  it('hides start from guests and disables the buttons while one is pending', () => {
    const scene = lobbyScene(lobby({ playerId: 'b', copied: true, readyPending: true }), area);
    expect(hud(scene.hud)).toMatchInlineSnapshot(`
      "
      bar: < -> leave · "SALA: CASAS" · copy ✓ · ⚙
      action: ready "PRONTO" emerald disabled
      "
    `);
  });

  it('cuts long names so the mark stays on the board', () => {
    const long = game({ players: [player('a', 'Maximiliano Augusto', { status: 'ready' })] });
    const scene = lobbyScene(lobby({ game: long }), area);
    expect(words(scene.tiles)).toMatchInlineSnapshot(`
      "
      player-a "MAXIMILIAN" @0,-6 stone
      status-a "✓" @0,5 emerald
      "
    `);
  });

  it('opens the settings drawer over the room: the host edits, guests read the room config', () => {
    const config = { time: 5, repetition: false };
    expect(hud(lobbyScene(lobby({ settings: true, config }), area).hud)).toContain('drawer: 5 min, repeat off\n');
    const guest = lobbyScene(lobby({ playerId: 'b', settings: true, config }), area);
    expect(hud(guest.hud)).toContain('drawer: 3 min, repeat on, read only\n');
  });
});

describe('game', () => {
  const playing = (extra: Partial<PlayState> = {}, state: Partial<GameState> = {}): PlayState => ({
    game: game({
      status: 'playing',
      turnPlayerId: 'a',
      chain: [{ word: 'casa', playerId: null }, { word: 'sapo', playerId: 'a' }, { word: 'pote', playerId: 'b' }],
      ...state,
    }),
    playerId: 'a',
    times: { startsIn: 0, match: 125, turn: 12 },
    typed: '',
    focused: true,
    pending: false,
    wordError: false,
    ...extra,
  });

  it('lays the chain out as a staircase over the input on my turn', () => {
    const scene = gameScene(playing({ typed: 'TE' }), area);
    expect(scene.fields).toEqual([{ id: 'word', row: 7, col: -6, length: 12, label: 'Palavra', value: 'TE' }]);
    expect(ascii(scene, area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...CASA........
      .....SAPO......
      .......POTE....
      ...............
      .TE|_________..
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
    expect(words(scene.tiles)).toMatchInlineSnapshot(`
      "
      chain-0 "CASA" @3,-4 stone
      chain-1 "SAPO" @4,-2 emerald/stone
      chain-2 "POTE" @5,0 emerald/amber
      chain-3 "TE__________" @7,-6 stone
      "
    `);
    expect(hud(scene.hud)).toMatchInlineSnapshot(`
      "
      clock: 125s 69%
      player: ANA rose 0 * 12s 80%
      player: BIA sky 0
      action: pass "PASSAR" rose
      action: submit "ENVIAR ↵" emerald primary
      "
    `);
  });

  it('dims the field for everyone else, with the turn on the HUD only', () => {
    const scene = gameScene(playing({ playerId: 'b' }), area);
    expect(scene.fields).toEqual([]);
    expect(ascii(scene, area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...CASA........
      .....SAPO......
      .......POTE....
      ...............
      .____________..
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
    const field = scene.tiles.filter((t) => t.key.startsWith(`${inputWordId(playing().game)}:`));
    expect(field.every((t) => t.disabled && t.variant === 'slot' && !t.active)).toBe(true);
    expect(hud(scene.hud)).toMatchInlineSnapshot(`
      "
      clock: 125s 69%
      player: ANA rose 0 * 12s 80%
      player: BIA sky 0
      action: pass "PASSAR" rose disabled
      action: submit "ENVIAR ↵" emerald primary disabled
      "
    `);
  });

  it('counts down to the start with a tile that grows each second', () => {
    const at = (startsIn: number) => gameScene(playing({ times: { startsIn, match: 180, turn: 15 } }), area);
    expect(ascii(at(3), area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ....PARTIDA....
      ...INICIA.EM...
      ...............
      ...............
      ...............
      ...............
      ......###......
      ......#3#......
      ......###......
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
    expect(ascii(at(1), area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ....PARTIDA....
      ...INICIA.EM...
      ...............
      ...............
      ....#######....
      ....#######....
      ....#######....
      ....###1###....
      ....#######....
      ....#######....
      ....#######....
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
    expect([3, 2, 1].map((n) => at(n).tiles.find((t) => t.key === 'countdown:0'))).toMatchInlineSnapshot(`
      [
        {
          "char": "3",
          "col": 0,
          "key": "countdown:0",
          "row": 3,
          "span": 3,
          "tone": "amber",
        },
        {
          "char": "2",
          "col": 0,
          "key": "countdown:0",
          "row": 3,
          "span": 5,
          "tone": "orange",
        },
        {
          "char": "1",
          "col": 0,
          "key": "countdown:0",
          "row": 3,
          "span": 7,
          "tone": "rose",
        },
      ]
    `);
    expect(hud(at(3).hud)).toMatchInlineSnapshot(`
      "
      clock: 180s 100%
      player: ANA rose 0
      player: BIA sky 0
      "
    `);
  });

  it('marks the clocks urgent near the end', () => {
    const scene = gameScene(playing({ times: { startsIn: 0, match: 30, turn: 5 } }), area);
    expect(hud(scene.hud)).toMatchInlineSnapshot(`
      "
      clock: 30s 17% urgent
      player: ANA rose 0 * 5s 33% urgent
      player: BIA sky 0
      action: pass "PASSAR" rose
      action: submit "ENVIAR ↵" emerald primary disabled
      "
    `);
  });

  it('turns a refused word rose', () => {
    const scene = gameScene(playing({ typed: 'XYZ', wordError: true }), area);
    expect(new Set(scene.tiles.filter((t) => t.key.startsWith('chain-3:')).map((t) => t.tone))).toEqual(new Set(['rose']));
  });

  it('disables pass and submit while a word is pending, and submit with nothing typed', () => {
    const pending = gameScene(playing({ typed: 'TELA', pending: true }), area).hud.actions;
    expect(pending.every((a) => a.disabled)).toBe(true);
    const empty = gameScene(playing(), area).hud.actions;
    expect(empty.map((a) => [a.id, !!a.disabled])).toEqual([['pass', false], ['submit', true]]);
  });

  it('types into the tiles of the next chain word, so an accepted word flies into place', () => {
    const before = playing({ typed: 'TELA' });
    const typing = gameScene(before, area).tiles.filter((t) => t.key.startsWith(`${inputWordId(before.game)}:`));
    const after = gameScene(playing({}, {
      turnPlayerId: 'b',
      chain: [...before.game.chain, { word: 'tela', playerId: 'a' }],
    }), area);
    const landed = after.tiles.filter((t) => t.key.startsWith('chain-3:'));
    expect(landed.map((t) => t.char).join('')).toBe('TELA');
    expect(keysOf(landed)).toEqual(keysOf(typing).slice(0, 4));
    expect(landed.every((t) => t.row === 5)).toBe(true);
  });

  it('scrolls old words off the top, keeping their keys while they climb', () => {
    const chain = ['casa', 'sapo', 'pote', 'tela', 'lago', 'gota', 'tampa', 'pato'].map((word) => ({ word, playerId: 'a' }));
    const tiles = chainTiles(game({ chain }), area);
    const ids = [...new Set(tiles.map((t) => t.key.split(':')[0]))];
    expect(ids).toHaveLength(CHAIN_ROWS);
    expect(ids[0]).toBe(`chain-${chain.length - CHAIN_ROWS}`);
    const rows = new Set(tiles.filter((t) => t.key.startsWith('chain-7:')).map((t) => t.row));
    expect([...rows]).toEqual([5]);
    expect(ascii(gameScene(playing({}, { chain }), area), area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      .TELA..........
      ...LAGO........
      .....GOTA......
      .......TAMPA...
      ..........PATO.
      ...............
      .|___________..
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
  });

  it('keeps the field over the actions and packs the HUD into one row when the keyboard is open', () => {
    const chain = ['casa', 'sapo', 'pote', 'tela', 'lago', 'gota'].map((word) => ({ word, playerId: 'a' }));
    const scene = gameScene(playing({ typed: 'TA' }, { chain }), compact);
    expect(scene.fields.map((f) => f.row)).toEqual([2]);
    expect(ascii(scene, compact)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ...............
      ...............
      .SAPO..........
      ...POTE........
      .....TELA......
      .......LAGO....
      .........GOTA..
      ...............
      .TA|_________..
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
    expect(scene.hud.compact).toBe(true);
  });

  it('fits as many chain words as the free rows hold, up to the maximum', () => {
    expect(playRows(area)).toEqual({ input: 7, chainBottom: 5, chainRows: CHAIN_ROWS });
    expect(playRows({ rows: 25, cols: 15, clear: { top: 1, bottom: 7 } })).toEqual({ input: 7, chainBottom: 5, chainRows: 5 });
    expect(playRows({ rows: 25, cols: 15, clear: { top: 3, bottom: 7 } })).toEqual({ input: 7, chainBottom: 5, chainRows: 3 });
    expect(playRows({ rows: 9, cols: 15 })).toEqual({ input: 4, chainBottom: 2, chainRows: 5 });
  });

  it('cuts a word longer than the board at the right edge, keeping its start', () => {
    const chain = [{ word: 'otorrinolaringologista', playerId: null }];
    const tiles = gameScene(playing({}, { chain }), area).tiles.filter((t) => t.key.startsWith('chain-0:'));
    expect(tiles.map((t) => t.char).join('')).toBe('OTORRINOLARINGO');
  });
});

