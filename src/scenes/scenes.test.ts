describe('notices', () => {
  const input = (notice: string | null): SceneInput => ({
    screen: 'home', game: null, playerId: null, times: { startsIn: 0, match: null, turn: null }, pending: new Set(),
    ui: {
      mode: 'join', player: '', room: '', settings: false, config: { time: 3, repetition: true },
      copied: false, typed: '', focused: null, wordError: false, notice,
    },
  });

  it('shows the latest notice above the actions on any screen', () => {
    expect(sceneFor(input('Sala não encontrada.'), area).hud.toast).toEqual({ text: 'SALA NÃO ENCONTRADA', tone: 'rose' });
    expect(sceneFor(input(null), area).hud.toast).toBeUndefined();
    expect(noticeText(' Palavra não existe. ')).toBe('PALAVRA NÃO EXISTE');
  });
});
