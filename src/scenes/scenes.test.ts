import { describe, expect, it } from 'vitest';
import type { GameState, Player } from '@src/protocol/schema';
import { endScene } from './end';
import { CHAIN_ROWS, chainTiles, gameScene, inputWordId, type PlayState } from './game';
import { homeScene, type HomeState } from './home';
import { loadingScene } from './loading';
import { lobbyScene } from './lobby';
import { settingsScene } from './settings';
import { ascii, words } from './testing';

const area = { rows: 17, cols: 15 };

const player = (id: string, name: string, extra: Partial<Player> = {}): Player =>
  ({ id, name, score: 0, status: 'waiting', color: null, ...extra });

const game = (extra: Partial<GameState> = {}): GameState => ({
  name: 'casas',
  status: 'lobby',
  players: [player('a', 'Ana', { color: 'red', status: 'ready' }), player('b', 'Bia', { color: 'blue' })],
  chain: [],
  hostId: 'a',
  turnPlayerId: null,
  config: { time: 3, repetition: true },
  startedAt: null,
  endsAt: null,
  turnDeadline: null,
  serverTime: 0,
  version: 1,
  ...extra,
});

const home = (extra: Partial<HomeState> = {}): HomeState =>
  ({ mode: 'menu', player: '', room: '', focused: null, loading: false, ...extra });

const keysOf = (tiles: { key: string }[]) => tiles.map((t) => t.key);

describe('home', () => {
  it('shows the menu', () => {
    const scene = homeScene(home(), area);
    expect(scene.fields).toEqual([]);
    expect(ascii(scene, area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ...............
      ...............
      ..CRIAR........
      ...............
      ...............
      ..ENTRAR.......
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      ...............
      "
    `);
    expect(words(scene.tiles)).toMatchInlineSnapshot(`
      "
      first "CRIAR" @-4,-5 amber -> host
      second "ENTRAR" @-1,-5 amber -> join
      "
    `);
  });

  it('opens the nickname and room fields to join, with the caret where typing goes', () => {
    const scene = homeScene(home({ mode: 'join', player: 'ANA', focused: 'player' }), area);
    expect(scene.fields.map((f) => [f.id, f.row, f.col, f.length])).toEqual([['player', -3, -5, 10], ['room', 0, -5, 6]]);
    expect(ascii(scene, area)).toMatchInlineSnapshot(`
      "
      ...............
      ...............
      ..<............
      ...............
      ..APELIDO......
      ..ANA|______...
      ...............
      ..SALA.........
      ..______.......
      ...............
      ...............
      ...............
      ............↵..
      ...............
      ...............
      ...............
      ...............
      "
    `);
  });

  it('keeps the menu words when a mode opens, so the letters change in place', () => {
    const menu = keysOf(homeScene(home(), area).tiles);
    const host = keysOf(homeScene(home({ mode: 'host' }), area).tiles);
    expect(host).toEqual(expect.arrayContaining(menu.filter((k) => k.startsWith('first:'))));
    expect(host.some((k) => k.startsWith('second:'))).toBe(false);
  });

  it('disables submit while the request is in flight', () => {
    const scene = homeScene(home({ mode: 'host', player: 'ANA', loading: true }), area);
    expect(words(scene.tiles.filter((t) => t.key.startsWith('submit:')))).toMatchInlineSnapshot(`
      "
      submit "..." @4,5 emerald
      "
    `);
  });
});

