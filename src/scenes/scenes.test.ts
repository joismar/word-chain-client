import { describe, expect, it } from 'vitest';
import type { GameState, Player } from '@src/protocol/schema';
import { endScene } from './end';
import { CHAIN_ROWS, chainTiles, gameScene, inputWordId, playRows, type PlayState } from './game';
import { homeScene, type HomeState } from './home';
import { noticeText, sceneFor, type SceneInput } from './index';
import { loadingScene } from './loading';
import { lobbyScene, type LobbyState } from './lobby';
import { ascii, hud, words } from './testing';

/** The HUD covers the top 4 rows (clock, chips) and the bottom 5 (message, actions). */
const area = { rows: 25, cols: 15, clear: { top: -8, bottom: 7 } };
/** A phone with the keyboard open: one HUD bar on top. */
const compact = { rows: 17, cols: 15, clear: { top: -5, bottom: 2 } };

const player = (id: string, name: string, extra: Partial<Player> = {}): Player =>
  ({ id, name, score: 0, status: 'waiting', color: null, ...extra });

const game = (extra: Partial<GameState> = {}): GameState => ({
  name: 'casas',
  status: 'lobby',
  players: [player('a', 'Ana', { color: 'red', status: 'ready' }), player('b', 'Bia', { color: 'blue' })],
  chain: [],
  hostId: 'a',
  turnPlayerId: null,
  config: { time: 3, repetition: true },
  startedAt: null,
  endsAt: null,
  turnDeadline: null,
  serverTime: 0,
  version: 1,
  ...extra,
});

const home = (extra: Partial<HomeState> = {}): HomeState =>
  ({ mode: 'menu', player: '', room: '', focused: null, loading: false, ...extra });

const keysOf = (tiles: { key: string }[]) => tiles.map((t) => t.key);

